//! `argo genesis revise` — operator-driven iteration on an
//! already-generated vertical.
//!
//! Walks the existing vertical tree and surgically updates one or
//! more of: the system prompt, the `[actions]` vocabulary, and the
//! eval-seed list. `[KEEP]…[/KEEP]` spans in the prompt survive.
//! See `docs/build-plan/streams/claude-genesis-iteration-cycle.md`.

use argo_genesis::action_suggest::suggest as suggest_actions;
use argo_genesis::eval_seed::{
    generate as generate_eval_seeds, suggested_actions_from_manifest, to_toml as eval_seeds_to_toml,
};
use argo_genesis::prompt_engineer::{revise as revise_prompt, PromptEngineerSession, PromptRevision};
use argo_types::{ArgoError, ArgoResult};
use argo_vertical::{
    ActionDeclaration, ActionRiskLevel, ActionsSection, ExecutorDeclaration, VerticalManifest,
};
use serde::Serialize;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone)]
pub struct GenesisReviseArgs {
    pub vertical: String,
    pub feedback: String,
    pub target: String,
    pub dry_run: bool,
    pub json: bool,
    /// Override the verticals discovery root. `None` = `argo_vertical::default_dir()`.
    pub verticals_dir: Option<PathBuf>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReviseTarget {
    Prompt,
    Actions,
    Eval,
    All,
}

impl std::str::FromStr for ReviseTarget {
    type Err = ArgoError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_lowercase().as_str() {
            "prompt" => Ok(Self::Prompt),
            "actions" => Ok(Self::Actions),
            "eval" => Ok(Self::Eval),
            "all" => Ok(Self::All),
            other => Err(ArgoError::Schema(format!(
                "unknown --target '{other}'; expected prompt|actions|eval|all"
            ))),
        }
    }
}

#[derive(Debug, Clone, Serialize)]
struct FileDiffSummary {
    path: String,
    changed_lines: usize,
}

#[derive(Debug, Clone, Serialize)]
struct ReviseOutcome {
    vertical: String,
    target: &'static str,
    dry_run: bool,
    written: Vec<FileDiffSummary>,
}

struct PendingWrite {
    path: PathBuf,
    before: String,
    after: String,
}

/// Sensible deviation: the brief asks for `async fn`, but every
/// primitive driven here is sync. We keep the handler sync to avoid
/// spinning up a tokio bridge for no benefit.
pub fn handle_revise(args: GenesisReviseArgs) -> ArgoResult<()> {
    let target = args.target.parse::<ReviseTarget>()?;
    let feedback = args.feedback.trim();
    if feedback.is_empty() {
        return Err(ArgoError::Schema("--feedback is empty".into()));
    }
    let vertical_dir = resolve_vertical_dir(&args.verticals_dir, &args.vertical)?;
    let manifest_path = vertical_dir.join("vertical.toml");
    let manifest_text = std::fs::read_to_string(&manifest_path).map_err(|e| {
        ArgoError::Provider(format!(
            "vertical '{}' missing vertical.toml at {}: {e}",
            args.vertical,
            manifest_path.display()
        ))
    })?;
    let mut manifest: VerticalManifest = toml::from_str(&manifest_text)
        .map_err(|e| ArgoError::Schema(format!("vertical.toml parse failed: {e}")))?;
    let charter = charter_from_manifest(&manifest);

    let mut writes: Vec<PendingWrite> = Vec::new();
    if matches!(target, ReviseTarget::Prompt | ReviseTarget::All) {
        writes.push(plan_prompt_revision(&vertical_dir, &manifest, &charter, feedback)?);
    }
    if matches!(target, ReviseTarget::Actions | ReviseTarget::All) {
        let (write, updated) =
            plan_action_revision(&manifest_path, &manifest_text, &manifest, &charter, feedback)?;
        manifest = updated;
        writes.push(write);
    }
    if matches!(target, ReviseTarget::Eval | ReviseTarget::All) {
        writes.push(plan_eval_revision(&vertical_dir, &manifest, &charter, feedback)?);
    }

    if !args.dry_run {
        for w in &writes {
            std::fs::write(&w.path, &w.after)
                .map_err(|e| ArgoError::Io(format!("failed to write {}: {e}", w.path.display())))?;
        }
    }

    emit_report(&args.vertical, target, args.dry_run, args.json, &writes);
    Ok(())
}

fn resolve_vertical_dir(override_dir: &Option<PathBuf>, name: &str) -> ArgoResult<PathBuf> {
    let root = override_dir.clone().unwrap_or_else(argo_vertical::default_dir);
    let dir = root.join(name);
    if !dir.is_dir() {
        return Err(ArgoError::Provider(format!(
            "vertical '{name}' not found under {}",
            root.display()
        )));
    }
    Ok(dir)
}

fn charter_from_manifest(manifest: &VerticalManifest) -> String {
    let desc = manifest.vertical.description.trim();
    desc.strip_prefix("Generated by Genesis from charter: ")
        .map(str::to_string)
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| {
            if desc.is_empty() {
                manifest.vertical.id.clone()
            } else {
                desc.to_string()
            }
        })
}

fn plan_prompt_revision(
    vertical_dir: &Path,
    manifest: &VerticalManifest,
    charter: &str,
    feedback: &str,
) -> ArgoResult<PendingWrite> {
    let prompt_rel = manifest
        .role
        .as_ref()
        .map(|r| r.system_prompt.clone())
        .filter(|p| !p.trim().is_empty())
        .unwrap_or_else(|| "prompts/system.md".to_string());
    let prompt_path = vertical_dir.join(&prompt_rel);
    let original = std::fs::read_to_string(&prompt_path).map_err(|e| {
        ArgoError::Provider(format!(
            "vertical missing system prompt at {}: {e}",
            prompt_path.display()
        ))
    })?;
    let mut session = PromptEngineerSession {
        role_description: charter.to_string(),
        current_prompt: original.clone(),
        history: vec![PromptRevision {
            rev: 0,
            prompt: original.clone(),
            feedback: None,
            locked_sections: extract_locked_sections(&original),
        }],
    };
    let next = revise_prompt(&mut session, feedback).map_err(ArgoError::from)?;
    Ok(PendingWrite { path: prompt_path, before: original, after: next.prompt.clone() })
}

fn extract_locked_sections(prompt: &str) -> Vec<String> {
    let (start_marker, end_marker) = ("[KEEP]", "[/KEEP]");
    let mut out = Vec::new();
    let mut offset = 0;
    while let Some(rel) = prompt[offset..].find(start_marker) {
        let start = offset + rel;
        let body = start + start_marker.len();
        let Some(rel_end) = prompt[body..].find(end_marker) else {
            break;
        };
        let end = body + rel_end + end_marker.len();
        out.push(prompt[start..end].to_string());
        offset = end;
    }
    out
}

fn plan_action_revision(
    manifest_path: &Path,
    manifest_text: &str,
    manifest: &VerticalManifest,
    charter: &str,
    feedback: &str,
) -> ArgoResult<(PendingWrite, VerticalManifest)> {
    let suggestions = suggest_actions(&format!("{charter} {feedback}"), 5).map_err(ArgoError::from)?;
    let mut updated = manifest.clone();
    let mut actions = updated
        .actions
        .clone()
        .unwrap_or(ActionsSection { actions: Default::default() });
    for s in suggestions {
        let action_type = s.id.to_ascii_lowercase().replace(['.', '-'], "_");
        if actions.actions.contains_key(&action_type) {
            continue;
        }
        let requires_approval = argo_genesis::safety_judge::matches_sensitive_verb(&action_type);
        actions.actions.insert(
            action_type,
            ActionDeclaration {
                risk: if requires_approval { ActionRiskLevel::High } else { ActionRiskLevel::Low },
                requires_approval,
                description: format!("Genesis revise: {} (feedback: {feedback})", s.reason),
                executor: ExecutorDeclaration::default(),
                ..ActionDeclaration::default()
            },
        );
    }
    updated.actions = Some(actions);
    let after = toml::to_string_pretty(&updated)
        .map_err(|e| ArgoError::Schema(format!("vertical.toml serialise failed: {e}")))?;
    Ok((
        PendingWrite {
            path: manifest_path.to_path_buf(),
            before: manifest_text.to_string(),
            after,
        },
        updated,
    ))
}

fn plan_eval_revision(
    vertical_dir: &Path,
    manifest: &VerticalManifest,
    charter: &str,
    feedback: &str,
) -> ArgoResult<PendingWrite> {
    let eval_path = vertical_dir.join("eval-seed.toml");
    let before = std::fs::read_to_string(&eval_path).unwrap_or_default();
    let actions = manifest
        .actions
        .as_ref()
        .map(suggested_actions_from_manifest)
        .unwrap_or_default();
    let seeds = generate_eval_seeds(&format!("{charter} {feedback}"), &actions)?;
    let after = eval_seeds_to_toml(&seeds);
    Ok(PendingWrite { path: eval_path, before, after })
}

fn emit_report(
    vertical: &str,
    target: ReviseTarget,
    dry_run: bool,
    json: bool,
    writes: &[PendingWrite],
) {
    let summaries: Vec<FileDiffSummary> = writes
        .iter()
        .map(|w| FileDiffSummary {
            path: w.path.display().to_string(),
            changed_lines: count_changed_lines(&w.before, &w.after),
        })
        .collect();
    if json {
        let outcome = ReviseOutcome {
            vertical: vertical.to_string(),
            target: target_label(target),
            dry_run,
            written: summaries,
        };
        println!(
            "{}",
            serde_json::to_string_pretty(&outcome).unwrap_or_else(|_| "{}".into())
        );
        return;
    }
    if dry_run {
        for w in writes {
            println!("--- {} (before)", w.path.display());
            println!("+++ {} (after)", w.path.display());
            print_minimal_diff(&w.before, &w.after);
        }
        println!(
            "dry-run: {} file(s) would change for vertical '{vertical}' ({})",
            summaries.len(),
            target_label(target)
        );
    } else {
        for s in &summaries {
            println!("wrote {} ({} changed lines)", s.path, s.changed_lines);
        }
        println!(
            "revised vertical '{vertical}' ({}); {} file(s) updated",
            target_label(target),
            summaries.len()
        );
    }
}

fn target_label(t: ReviseTarget) -> &'static str {
    match t {
        ReviseTarget::Prompt => "prompt",
        ReviseTarget::Actions => "actions",
        ReviseTarget::Eval => "eval",
        ReviseTarget::All => "all",
    }
}

fn count_changed_lines(before: &str, after: &str) -> usize {
    let b: BTreeSet<&str> = before.lines().collect();
    let a: BTreeSet<&str> = after.lines().collect();
    let removed = before.lines().filter(|l| !a.contains(*l)).count();
    let added = after.lines().filter(|l| !b.contains(*l)).count();
    removed + added
}

fn print_minimal_diff(before: &str, after: &str) {
    let b: BTreeSet<&str> = before.lines().collect();
    let a: BTreeSet<&str> = after.lines().collect();
    for line in before.lines().filter(|l| !a.contains(*l)) {
        println!("- {line}");
    }
    for line in after.lines().filter(|l| !b.contains(*l)) {
        println!("+ {line}");
    }
}

