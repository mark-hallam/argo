//! `argo replay export <session_id> --out <path> [--uncompressed] [--sanitize]`
//! — emit a self-contained tar/tar.gz of one session for offline
//! replay or support hand-off.
//!
//! See `crates/argo-replay/src/bundle.rs` for the pure assembly +
//! sanitization logic; this handler does the database reads and
//! filesystem write.
use crate::home::{db_path, ensure_dir, resolve_home};
use argo_audit::{rows_for_session, verify_session, ExportedRow};
use argo_replay::bundle::{build_bundle, sanitize_value, BundleOptions, ReplayBundleFile};
use argo_store::SessionStore;
use argo_types::{ArgoError, ArgoResult, SessionId};
use std::path::Path;

const README: &str = "# Argo session bundle\n\n\
This tarball captures one Argo session for offline analysis or support hand-off.\n\n\
## Contents\n\n\
- `manifest.toml` — session metadata, content sha256, sanitized flag.\n\
- `audit/chain.jsonl` — full audit chain rows, one JSON object per line, in seq order.\n\
- `audit/verify.txt` — `argo audit verify-chain` output captured at export time.\n\
- `skills/<id>.json` — attached skill ids and version stamps.\n\
- `bundle/action-<seq>.json` — per-tool-call request + result blobs.\n\
- `memory/` — placeholder; per-session memory walks land in a follow-up brief.\n\n\
## Replay\n\n\
1. `tar xzf <bundle>.tar.gz -C ./session-replay/`\n\
2. Re-verify chain offline: `argo audit verify-chain --from-file ./session-replay/audit/chain.jsonl`.\n\n\
See `docs/skycot/operator/incident-response.md` for the support-hand-off flow.\n";

/// Top-level entrypoint for `argo replay export`.
pub async fn run(
    session_id_raw: &str,
    out: &str,
    uncompressed: bool,
    sanitize: bool,
) -> ArgoResult<()> {
    let out_path = Path::new(out);
    ensure_parent_dir(out_path)?;
    let cwd = std::env::current_dir().map_err(|e| ArgoError::Io(format!("current_dir: {e}")))?;
    let home = resolve_home(&cwd)?;
    ensure_dir(&home)?;
    let store = SessionStore::open(&db_path(&home)).await?;
    store.migrate().await?;
    let session_id = parse_session_id(session_id_raw)?;
    let header = store
        .get_session(session_id)
        .await?
        .ok_or_else(|| ArgoError::Provider(format!("session not found: {session_id_raw}")))?;
    let rows = rows_for_session(&store, session_id).await?;
    let verify = verify_session(&store, session_id).await?;
    let attached = attached_skill_ids(&store, session_id).await?;
    let manifest_prefix = render_manifest_prefix(&header, &rows, sanitize);
    let files = build_files(&rows, &verify, &attached)?;
    let bytes = build_bundle(
        files,
        manifest_prefix,
        BundleOptions {
            sanitize,
            compressed: !uncompressed,
            readme: README,
        },
    )?;
    std::fs::write(out_path, &bytes)
        .map_err(|e| ArgoError::Io(format!("write {}: {e}", out_path.display())))?;
    eprintln!(
        "replay export: wrote {} bytes to {} ({} audit rows; sanitize={})",
        bytes.len(),
        out_path.display(),
        rows.len(),
        sanitize
    );
    Ok(())
}

fn ensure_parent_dir(path: &Path) -> ArgoResult<()> {
    let Some(parent) = path.parent() else {
        return Ok(());
    };
    if parent.as_os_str().is_empty() || parent.exists() {
        return Ok(());
    }
    Err(ArgoError::Io(format!(
        "output parent does not exist: {} (create it before --out)",
        parent.display()
    )))
}

fn parse_session_id(raw: &str) -> ArgoResult<SessionId> {
    uuid::Uuid::parse_str(raw)
        .map(SessionId)
        .map_err(|e| ArgoError::Schema(format!("invalid session id '{raw}': {e}")))
}

fn render_manifest_prefix(
    header: &argo_store::SessionHeader,
    rows: &[ExportedRow],
    sanitize: bool,
) -> String {
    let mut title = header
        .title
        .clone()
        .unwrap_or_else(|| "(untitled)".to_string());
    if sanitize {
        let mut wrap = serde_json::Value::String(title.clone());
        sanitize_value(&mut wrap);
        if let serde_json::Value::String(s) = wrap {
            title = s;
        }
    }
    let end_ts = header.ended_at.map(|t| t.to_rfc3339()).unwrap_or_default();
    let mut out = String::new();
    out.push_str("# Generated by `argo replay export` — see README.md for replay steps.\n");
    out.push_str(&format!("session_id = \"{}\"\n", header.id.0));
    out.push_str(&format!("tenant_id = \"{}\"\n", header.tenant_id.0));
    out.push_str(&format!("workspace_id = \"{}\"\n", header.workspace_id.0));
    out.push_str(&format!("title = {}\n", toml_string(&title)));
    out.push_str(&format!("model = {}\n", toml_string(&header.model)));
    out.push_str(&format!("provider = {}\n", toml_string(&header.provider)));
    out.push_str(&format!(
        "start_ts = \"{}\"\n",
        header.started_at.to_rfc3339()
    ));
    out.push_str(&format!("end_ts = \"{end_ts}\"\n"));
    out.push_str(&format!(
        "argo_version = \"{}\"\n",
        env!("CARGO_PKG_VERSION")
    ));
    out.push_str(&format!("audit_row_count = {}\n", rows.len()));
    out
}

fn toml_string(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

fn build_files(
    rows: &[ExportedRow],
    verify: &argo_audit::VerifyReport,
    attached_skills: &[(String, i64)],
) -> ArgoResult<Vec<ReplayBundleFile>> {
    let mut files = Vec::new();
    files.push(ReplayBundleFile::json(
        "audit/chain.jsonl",
        render_chain_jsonl(rows)?,
    ));
    files.push(ReplayBundleFile::raw(
        "audit/verify.txt",
        render_verify_txt(verify).into_bytes(),
    ));
    for (skill_id, attached_at) in attached_skills {
        let body = serde_json::to_vec_pretty(&serde_json::json!({
            "skill_id": skill_id,
            "attached_at_micros": attached_at,
        }))
        .map_err(|e| ArgoError::Provider(format!("serialize skill: {e}")))?;
        files.push(ReplayBundleFile::json(
            format!("skills/{skill_id}.json"),
            body,
        ));
    }
    for row in rows {
        if row.kind != "tool_call" && row.kind != "tool_result" {
            continue;
        }
        let body = serde_json::to_vec_pretty(&serde_json::json!({
            "seq": row.seq,
            "id": row.id,
            "kind": row.kind,
            "payload": row.payload,
            "created_at_micros": row.created_at_micros,
        }))
        .map_err(|e| ArgoError::Provider(format!("serialize action: {e}")))?;
        files.push(ReplayBundleFile::json(
            format!("bundle/action-{}.json", row.seq),
            body,
        ));
    }
    Ok(files)
}

fn render_chain_jsonl(rows: &[ExportedRow]) -> ArgoResult<Vec<u8>> {
    let mut out = Vec::new();
    for row in rows {
        let line = serde_json::to_vec(row)
            .map_err(|e| ArgoError::Provider(format!("serialize audit row: {e}")))?;
        out.extend_from_slice(&line);
        out.push(b'\n');
    }
    Ok(out)
}

fn render_verify_txt(report: &argo_audit::VerifyReport) -> String {
    let mut out = String::new();
    out.push_str(&format!("rows: {}\n", report.rows));
    out.push_str(&format!("ok: {}\n", report.ok));
    out.push_str(&format!("breaks: {}\n", report.breaks.len()));
    for b in &report.breaks {
        out.push_str(&format!(
            "  seq={} kind={} reason={}\n",
            b.seq, b.kind, b.reason
        ));
    }
    out
}

async fn attached_skill_ids(
    store: &SessionStore,
    session_id: SessionId,
) -> ArgoResult<Vec<(String, i64)>> {
    let rows: Vec<(Vec<u8>, i64)> = sqlx::query_as(
        "SELECT skill_id, attached_at FROM session_skill \
         WHERE session_id = ? ORDER BY skill_id ASC",
    )
    .bind(session_id.0.as_bytes().as_slice())
    .fetch_all(store.pool())
    .await
    .map_err(|e| ArgoError::Provider(format!("session_skill lookup: {e}")))?;
    Ok(rows
        .into_iter()
        .map(|(id, attached)| {
            let skill = uuid::Uuid::from_slice(&id)
                .map(|u| u.to_string())
                .unwrap_or_else(|_| hex::encode(&id));
            (skill, attached)
        })
        .collect())
}

