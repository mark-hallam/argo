//! Operator-perspective product e2e test
//! (Stream `claude-end-to-end-product-test`).
//!
//! Distinct from `e2e_v1_demo.rs` (which exercises internal library
//! APIs): every step here drives the actual `argo` binary so a
//! reviewer can read the test like an operator's terminal session.
//!
//! 9-step flow:
//!   1. Fresh ARGO_HOME tempdir
//!   2. `argo onboard --non-interactive --config <fixtures/onboarding-min.toml>`
//!   3. Verify `<workspace>/argo.toml` + `.argo/credentials.toml` exist
//!   4. Verify `<workspace>/verticals/maya/vertical.toml` exists
//!      (Stage 5 of onboarding wrote it via `argo_genesis::plan`)
//!   5. Inject a sample task as a worker_action memory row
//!      (script-injected; mirrors what the in-process emit module
//!      writes at runtime)
//!   6. `argo worker actions list --json` — assert the row shows
//!      up under the vertical, in `pending` state
//!   7. `argo worker actions approve` → `... execute` → `... complete`
//!      — drives the action through the auto-approval gate's
//!      transition path and the mock executor's stamp
//!   8. `argo worker actions show <id> --json` — assert final state
//!      is `completed` and `executed_at` is populated
//!   9. Cleanup is automatic — `tempfile::tempdir` drops on scope
//!      exit (idempotent even if an assertion panics)
//!
//! Total runtime is well under 60s (no LLM calls; uses the
//! deterministic offline genesis + stub mock executor stamp).

mod common;

use common::product_e2e_helpers::{
    assert_success, current_action_state, fixtures_dir, inject_pending_action, json_cmd, run_argo,
};

#[test]
fn product_e2e_full_flow_passes_offline() {
    // Step 1 — Fresh ARGO_HOME tempdir.
    let home = tempfile::tempdir().expect("tempdir for ARGO_HOME");
    let work = tempfile::tempdir().expect("tempdir for workspace");
    let fixture_path = fixtures_dir().join("onboarding-min.toml");
    assert!(
        fixture_path.exists(),
        "fixture {} missing — test cannot run",
        fixture_path.display()
    );

    // Step 2 — Drive `argo onboard --non-interactive --config <fixture>`.
    let onboard_envelope = json_cmd(
        "step 2: argo onboard --non-interactive",
        home.path(),
        work.path(),
        &[
            "onboard",
            "--non-interactive",
            "--json",
            "--config",
            fixture_path.to_str().expect("utf-8 fixture path"),
        ],
    );
    assert_eq!(
        onboard_envelope["count"].as_u64(),
        Some(7),
        "onboard envelope must report all 7 stages"
    );
    assert_eq!(
        onboard_envelope["any_fail"].as_bool(),
        Some(false),
        "no stage may fail; envelope: {}",
        serde_json::to_string_pretty(&onboard_envelope).unwrap_or_default()
    );

    // Step 3 — workspace + credentials.toml exist.
    assert!(
        work.path().join("argo.toml").exists(),
        "step 3: argo.toml must exist after Workspace stage"
    );
    let creds_path = work.path().join(".argo/credentials.toml");
    assert!(
        creds_path.exists(),
        "step 3: credentials.toml must exist after Credentials stage"
    );
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = std::fs::metadata(&creds_path)
            .expect("stat credentials.toml")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(mode, 0o600, "credentials.toml must be mode 0600");
    }

    // Step 4 — vertical was generated by genesis.
    let vertical_dir = work.path().join("verticals/maya");
    assert!(
        vertical_dir.join("vertical.toml").exists(),
        "step 4: verticals/maya/vertical.toml must exist after First worker stage"
    );
    let manifest_id = read_vertical_id(&vertical_dir.join("vertical.toml"));
    assert!(
        !manifest_id.is_empty(),
        "step 4: vertical manifest must declare an id"
    );

    // Step 5 — Inject a sample task as a worker_action memory row
    // through the standard CLI surface. The action_type must be one
    // the genesis-generated vertical declares — we use
    // `escalate_ticket` (requires_approval=true so the auto-approval
    // gate's `pending → approved` transition is exercisable).
    let template = serde_json::json!({
        "schema_key": "worker_action",
        "job_id": "product-e2e-job-1",
        "action_type": "escalate_ticket",
        "risk_level": "medium",
        "requires_approval": true,
        "payload": {
            "subject": "Welcome to SKYCOT",
            "body": "Thank you for signing up — your first worker is ready.",
            "to": "operator@example.com"
        }
    });
    let action_id = inject_pending_action(
        "step 5: inject pending action",
        home.path(),
        work.path(),
        &manifest_id,
        &template,
    );

    // Step 6 — `argo worker actions list --json` finds the row.
    let list_out = run_argo(
        home.path(),
        work.path(),
        &[
            "worker",
            "actions",
            "list",
            "--vertical",
            &manifest_id,
            "--state",
            "pending",
            "--json",
        ],
    );
    assert_success("step 6: worker actions list", &list_out);
    let stdout = String::from_utf8_lossy(&list_out.stdout).to_string();
    assert!(
        stdout.contains(&action_id),
        "step 6: list (--state pending) must include the just-injected action_id\nstdout:\n{stdout}"
    );
    assert_eq!(
        current_action_state(home.path(), work.path(), &action_id),
        "pending",
        "step 6: action must currently be `pending`"
    );

    // Step 7 — Approve → execute → complete via the public CLI.
    let approve = run_argo(
        home.path(),
        work.path(),
        &[
            "worker",
            "actions",
            "approve",
            &action_id,
            "--approved-by",
            "operator@example.com",
            "--note",
            "auto-approved for e2e smoke",
            "--json",
        ],
    );
    assert_success("step 7a: worker actions approve", &approve);
    assert_eq!(
        current_action_state(home.path(), work.path(), &action_id),
        "approved",
        "step 7a: action must transition to `approved`"
    );

    let execute = run_argo(
        home.path(),
        work.path(),
        &["worker", "actions", "execute", &action_id, "--json"],
    );
    assert_success("step 7b: worker actions execute", &execute);
    assert_eq!(
        current_action_state(home.path(), work.path(), &action_id),
        "executing",
        "step 7b: action must transition to `executing`"
    );

    let complete = run_argo(
        home.path(),
        work.path(),
        &[
            "worker",
            "actions",
            "complete",
            &action_id,
            "--note",
            "draft email saved to outputs/",
            "--json",
        ],
    );
    assert_success("step 7c: worker actions complete", &complete);

    // Step 8 — Final state + executed_at populated.
    let show_envelope = json_cmd(
        "step 8: worker actions show",
        home.path(),
        work.path(),
        &["worker", "actions", "show", &action_id, "--json"],
    );
    assert_eq!(
        show_envelope["state"].as_str(),
        Some("completed"),
        "step 8: final state must be `completed`; envelope: {}",
        serde_json::to_string_pretty(&show_envelope).unwrap_or_default()
    );
    assert!(
        show_envelope["executed_at"].as_str().is_some_and(|s| !s.is_empty()),
        "step 8: `executed_at` must be populated; envelope: {}",
        serde_json::to_string_pretty(&show_envelope).unwrap_or_default()
    );

    // Step 9 — Cleanup is automatic via Drop on `home` and `work`.
    drop(home);
    drop(work);
}

#[test]
fn missing_onboard_config_fails_cleanly() {
    let home = tempfile::tempdir().unwrap();
    let work = tempfile::tempdir().unwrap();
    // No fixture, no .argo/onboarding.toml — the loader returns
    // OnboardConfig::default(), so onboarding still completes;
    // every config-driven stage should Skip rather than Fail.
    let envelope = json_cmd(
        "missing-config onboard",
        home.path(),
        work.path(),
        &["onboard", "--non-interactive", "--json"],
    );
    assert_eq!(envelope["count"].as_u64(), Some(7));
    assert_eq!(envelope["any_fail"].as_bool(), Some(false));
    let stages = envelope["stages"].as_array().expect("stages array");
    let credentials = stages
        .iter()
        .find(|s| s["name"].as_str() == Some("Credentials"))
        .expect("credentials stage");
    assert_eq!(
        credentials["status"].as_str(),
        Some("skip"),
        "credentials must SKIP when no config provided"
    );
}

fn read_vertical_id(path: &std::path::Path) -> String {
    let body = std::fs::read_to_string(path).unwrap_or_else(|e| {
        panic!("read {}: {e}", path.display());
    });
    let parsed: toml::Value = toml::from_str(&body).unwrap_or_else(|e| {
        panic!("parse {}: {e}", path.display());
    });
    parsed
        .get("vertical")
        .and_then(|v| v.get("id"))
        .and_then(|v| v.as_str())
        .unwrap_or_default()
        .to_string()
}
