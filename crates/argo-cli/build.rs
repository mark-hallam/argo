//! Capture build-time facts (git SHA + date, target triple, rustc
//! version, profile, enabled features) into `$OUT_DIR/build_info.rs`
//! so `argo --version` and `argo doctor` can surface them at runtime.
//!
//! Every probe falls back to `"unknown"` on failure — building from a
//! tarball without `.git/`, or with `git` unavailable on `PATH`, must
//! not break the build (`mission-cli-version-doctor-extras`
//! "Hidden constraints" + acceptance criteria #6).
use std::process::Command;

fn main() {
    // Re-run when the git HEAD moves so the embedded SHA stays
    // current; `.git/HEAD` is the cheapest pointer that changes on
    // every checkout / commit.
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../.git/HEAD");
    println!("cargo:rerun-if-changed=../../.git/refs/heads");
    println!("cargo:rerun-if-env-changed=PROFILE");
    println!("cargo:rerun-if-env-changed=TARGET");

    let git_sha = probe("git", &["rev-parse", "--short=7", "HEAD"]);
    let git_date = probe("git", &["log", "-1", "--date=short", "--format=%cd"]);
    let target = std::env::var("TARGET").unwrap_or_else(|_| "unknown".into());
    let profile = std::env::var("PROFILE").unwrap_or_else(|_| "unknown".into());
    let rustc_bin = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let rustc_version = probe(&rustc_bin, &["--version"]);
    let features = enabled_features();

    let out_dir = std::env::var("OUT_DIR").expect("cargo always sets OUT_DIR for build scripts");
    let dest = std::path::Path::new(&out_dir).join("build_info.rs");
    let body = format!(
        "// Auto-generated by build.rs; do not edit.\n\
         pub const GIT_SHA: &str = {git_sha:?};\n\
         pub const GIT_DATE: &str = {git_date:?};\n\
         pub const TARGET: &str = {target:?};\n\
         pub const PROFILE: &str = {profile:?};\n\
         pub const RUSTC_VERSION: &str = {rustc_version:?};\n\
         pub const FEATURES: &[&str] = &{features:?};\n",
    );
    std::fs::write(&dest, body).expect("write build_info.rs to OUT_DIR");
}

/// Run a probe command; on any failure (non-zero exit, missing
/// binary, non-UTF-8 output) emit a cargo warning and return
/// `"unknown"`. Never aborts the build.
fn probe(bin: &str, args: &[&str]) -> String {
    let output = match Command::new(bin).args(args).output() {
        Ok(out) => out,
        Err(e) => {
            println!("cargo:warning=build_info: `{bin} {args:?}` not runnable: {e}");
            return "unknown".into();
        }
    };
    if !output.status.success() {
        println!(
            "cargo:warning=build_info: `{bin} {args:?}` exited {status}",
            status = output.status,
        );
        return "unknown".into();
    }
    match String::from_utf8(output.stdout) {
        Ok(s) => s.trim().to_string(),
        Err(_) => "unknown".into(),
    }
}

/// Enumerate the features cargo enabled for this crate by walking
/// `CARGO_FEATURE_<NAME>=1` env vars cargo sets for build scripts.
/// Names are lowercased + dashes restored to match the
/// `[features]` table.
fn enabled_features() -> Vec<String> {
    let mut features: Vec<String> = std::env::vars()
        .filter_map(|(k, _)| k.strip_prefix("CARGO_FEATURE_").map(|n| {
            n.to_lowercase().replace('_', "-")
        }))
        .collect();
    features.sort();
    features
}
