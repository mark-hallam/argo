/// Storage tier for a memory row.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MemoryLayer {
    /// Hot, verbatim memory from the last 30 days.
    Recent,
    /// Older rows indexed for hybrid retrieval.
    Indexed,
    /// Worker/month summaries generated by the nightly summary job.
    Summary,
}

impl MemoryLayer {
    /// Database label for the layer.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Recent => "recent",
            Self::Indexed => "indexed",
            Self::Summary => "summary",
        }
    }

    /// Parse a database label.
    pub fn parse(s: &str) -> ArgoResult<Self> {
        match s {
            "recent" => Ok(Self::Recent),
            "indexed" => Ok(Self::Indexed),
            "summary" => Ok(Self::Summary),
            other => Err(ArgoError::Schema(format!(
                "memory_entry.layer: unknown layer {other}"
            ))),
        }
    }
}

/// A memory entry annotated with its storage layer.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LayeredMemoryEntry {
    /// The underlying append-only memory row.
    pub entry: MemoryEntry,
    /// Layer where the row is stored.
    pub layer: MemoryLayer,
}

/// A retrieved indexed row with its hybrid retrieval score.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ScoredMemoryEntry {
    /// The retrieved memory row.
    pub entry: MemoryEntry,
    /// Hybrid lexical/vector score. Larger is better.
    pub score: f32,
}

impl MemoryStore {
    /// Ensure the additive layer/namespace/index schema exists.
    pub(crate) async fn ensure_layer_schema(&self) -> ArgoResult<()> {
        let pool = self.pool();
        let _sqlite_vec_init: unsafe extern "C" fn() = sqlite_vec::sqlite3_vec_init;
        if !memory_column_exists(pool, "layer").await? {
            exec_schema(
                pool,
                "ALTER TABLE memory_entry ADD COLUMN layer TEXT NOT NULL DEFAULT 'recent'",
            )
            .await?;
        }
        if !memory_column_exists(pool, "tenant_id").await? {
            exec_schema(pool, "ALTER TABLE memory_entry ADD COLUMN tenant_id BLOB").await?;
        }
        if !memory_column_exists(pool, "worker_id").await? {
            exec_schema(pool, "ALTER TABLE memory_entry ADD COLUMN worker_id BLOB").await?;
        }
        if !memory_column_exists(pool, "memory_scope").await? {
            exec_schema(
                pool,
                "ALTER TABLE memory_entry ADD COLUMN memory_scope TEXT",
            )
            .await?;
        }
        exec_schema(
            pool,
            "CREATE INDEX IF NOT EXISTS idx_memory_entry_layer \
             ON memory_entry(workspace_id, layer, learned_at)",
        )
        .await?;
        exec_schema(
            pool,
            "CREATE INDEX IF NOT EXISTS idx_memory_entry_ns_layer \
             ON memory_entry(tenant_id, worker_id, memory_scope, layer, learned_at)",
        )
        .await?;
        exec_schema(
            pool,
            "CREATE VIRTUAL TABLE IF NOT EXISTS memory_entry_fts USING fts5(\
             entry_id UNINDEXED, body, tokenize='unicode61 remove_diacritics 2')",
        )
        .await?;
        exec_schema(
            pool,
            "CREATE TABLE IF NOT EXISTS memory_embedding (\
             entry_id BLOB PRIMARY KEY REFERENCES memory_entry(id) ON DELETE CASCADE, \
             model TEXT NOT NULL, dims INTEGER NOT NULL, vector_json TEXT NOT NULL, \
             created_at INTEGER NOT NULL)",
        )
        .await?;
        let _ = sqlx::query(
            "CREATE VIRTUAL TABLE IF NOT EXISTS memory_vec_index USING vec0(\
             entry_id TEXT PRIMARY KEY, embedding FLOAT[64])",
        )
        .execute(pool)
        .await;
        Ok(())
    }

    /// Append a recent memory row inside a tenant/worker namespace.
    pub async fn append_in_namespace(
        &self,
        ns: &MemoryNs,
        workspace_id: WorkspaceId,
        file: MemoryFile,
        body: String,
        learned_in: Option<SessionId>,
    ) -> ArgoResult<MemoryEntry> {
        self.append_in_namespace_with_layer(
            ns,
            workspace_id,
            file,
            body,
            learned_in,
            MemoryLayer::Recent,
        )
        .await
    }

    /// Append a memory row in an explicit layer inside a tenant/worker namespace.
    pub async fn append_in_namespace_with_layer(
        &self,
        ns: &MemoryNs,
        workspace_id: WorkspaceId,
        file: MemoryFile,
        body: String,
        learned_in: Option<SessionId>,
        layer: MemoryLayer,
    ) -> ArgoResult<MemoryEntry> {
        self.ensure_layer_schema().await?;
        let id = Uuid::now_v7();
        let learned_at = Utc::now();
        let hash = sha256(&body);
        sqlx::query(
            "INSERT INTO memory_entry (id, workspace_id, file, body, learned_in, \
             learned_at, hash, tenant_id, worker_id, memory_scope, layer) \
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        )
        .bind(id.as_bytes().as_slice())
        .bind(workspace_id.0.as_bytes().as_slice())
        .bind(file.filename())
        .bind(&body)
        .bind(learned_in.map(|s| s.0.as_bytes().to_vec()))
        .bind(learned_at.timestamp_micros())
        .bind(hash.as_slice())
        .bind(ns.tenant_id.0.as_bytes().as_slice())
        .bind(ns.worker_id.0.as_bytes().as_slice())
        .bind(scope_as_str(ns.scope))
        .bind(layer.as_str())
        .execute(self.pool())
        .await
        .map_err(|e| ArgoError::Provider(format!("memory append_in_namespace: {e}")))?;
        Ok(MemoryEntry {
            id,
            workspace_id,
            file,
            body,
            learned_in,
            learned_at,
            superseded_by: None,
            hash,
            lock: Lock::None,
            vertical_id: None,
        })
    }

    /// Promote recent rows older than `days` into the indexed layer.
    pub async fn promote_recent_older_than(&self, days: i64) -> ArgoResult<u64> {
        self.promote_recent_before(Utc::now() - chrono::Duration::days(days))
            .await
    }

    /// Promote recent rows older than `cutoff` into the indexed layer.
    pub async fn promote_recent_before(&self, cutoff: DateTime<Utc>) -> ArgoResult<u64> {
        self.ensure_layer_schema().await?;
        let changed = sqlx::query(
            "UPDATE memory_entry SET layer = 'indexed' \
             WHERE layer = 'recent' AND learned_at < ? AND superseded_by IS NULL",
        )
        .bind(cutoff.timestamp_micros())
        .execute(self.pool())
        .await
        .map_err(|e| ArgoError::Provider(format!("memory promote_recent_before: {e}")))?
        .rows_affected();
        self.refresh_indexed_embeddings(&Voyage3EmbeddingProvider)
            .await?;
        Ok(changed)
    }

    /// Return top-k indexed rows from one namespace using FTS5 + vector scoring.
    pub async fn query(
        &self,
        ns: &MemoryNs,
        query: &str,
        k: usize,
    ) -> ArgoResult<Vec<MemoryEntry>> {
        Ok(self
            .query_scored(ns, query, k)
            .await?
            .into_iter()
            .map(|e| e.entry)
            .collect())
    }

    /// Return top-k indexed rows with hybrid scores.
    pub async fn query_scored(
        &self,
        ns: &MemoryNs,
        query: &str,
        k: usize,
    ) -> ArgoResult<Vec<ScoredMemoryEntry>> {
        if k == 0 {
            return Ok(Vec::new());
        }
        let provider = Voyage3EmbeddingProvider;
        self.ensure_layer_schema().await?;
        self.refresh_indexed_embeddings(&provider).await?;
        let query_vec = provider.embed(query)?;
        let fts_scores = self.fts_scores(query).await?;
        let mut scored = Vec::new();
        for row in self.layer_rows(ns, MemoryLayer::Indexed).await? {
            let vector = row
                .vector_json
                .as_deref()
                .and_then(vector_from_json)
                .unwrap_or_else(|| hash_embedding(&row.body));
            let semantic = cosine(&query_vec, &vector);
            let lexical = fts_scores
                .get(&hex::encode_upper(&row.id))
                .map(|rank| 1.0 / (1.0 + rank.abs() as f32))
                .unwrap_or(0.0);
            let entry = row.into_memory_entry()?;
            scored.push(ScoredMemoryEntry {
                entry,
                score: semantic + lexical,
            });
        }
        scored.sort_by(|a, b| {
            b.score
                .partial_cmp(&a.score)
                .unwrap_or(Ordering::Equal)
                .then_with(|| b.entry.learned_at.cmp(&a.entry.learned_at))
        });
        scored.truncate(k);
        Ok(scored)
    }

    /// Compose summaries, recents, and relevant indexed rows for an action.
    pub async fn compose_context(&self, ns: &MemoryNs, action_id: &str) -> ArgoResult<ContextPack> {
        let mut rows = Vec::new();
        rows.extend(self.layered_entries(ns, MemoryLayer::Summary).await?);
        rows.extend(self.layered_entries(ns, MemoryLayer::Recent).await?);
        let mut seen: HashSet<Uuid> = rows.iter().map(|r| r.entry.id).collect();
        for scored in self.query_scored(ns, action_id, 24).await? {
            if seen.insert(scored.entry.id) {
                rows.push(LayeredMemoryEntry {
                    entry: scored.entry,
                    layer: MemoryLayer::Indexed,
                });
            }
        }
        Ok(pack_context(rows))
    }

    pub(crate) async fn layered_entries(
        &self,
        ns: &MemoryNs,
        layer: MemoryLayer,
    ) -> ArgoResult<Vec<LayeredMemoryEntry>> {
        self.layer_rows(ns, layer)
            .await?
            .into_iter()
            .map(|row| {
                Ok(LayeredMemoryEntry {
                    layer: MemoryLayer::parse(&row.layer)?,
                    entry: row.into_memory_entry()?,
                })
            })
            .collect()
    }

    async fn layer_rows(&self, ns: &MemoryNs, layer: MemoryLayer) -> ArgoResult<Vec<LayerRow>> {
        let rows = sqlx::query_as::<_, LayerRow>(
            "SELECT m.id, m.workspace_id, m.file, m.body, m.learned_in, \
             m.learned_at, m.superseded_by, m.hash, l.lock, m.vertical_id, \
             m.layer, e.vector_json \
             FROM memory_entry m \
             LEFT JOIN memory_lock l ON l.entry_id = m.id \
             LEFT JOIN memory_embedding e ON e.entry_id = m.id \
             WHERE m.tenant_id = ? AND m.worker_id = ? AND m.memory_scope = ? \
               AND m.layer = ? AND m.superseded_by IS NULL \
             ORDER BY m.learned_at ASC",
        )
        .bind(ns.tenant_id.0.as_bytes().as_slice())
        .bind(ns.worker_id.0.as_bytes().as_slice())
        .bind(scope_as_str(ns.scope))
        .bind(layer.as_str())
        .fetch_all(self.pool())
        .await
        .map_err(|e| ArgoError::Provider(format!("memory layer_rows: {e}")))?;
        Ok(rows)
    }

    async fn refresh_indexed_embeddings(&self, provider: &dyn EmbeddingProvider) -> ArgoResult<()> {
        self.ensure_layer_schema().await?;
        let rows = sqlx::query("SELECT id, body FROM memory_entry WHERE layer = 'indexed'")
            .fetch_all(self.pool())
            .await
            .map_err(|e| ArgoError::Provider(format!("memory indexed scan: {e}")))?;
        for row in rows {
            let id: Vec<u8> = row
                .try_get("id")
                .map_err(|e| ArgoError::Provider(format!("memory indexed id: {e}")))?;
            let body: String = row
                .try_get("body")
                .map_err(|e| ArgoError::Provider(format!("memory indexed body: {e}")))?;
            let vector = provider.embed(&body)?;
            let vector_json = vector_to_json(&vector)?;
            let entry_hex = hex::encode_upper(&id);
            sqlx::query("DELETE FROM memory_entry_fts WHERE entry_id = ?")
                .bind(&entry_hex)
                .execute(self.pool())
                .await
                .map_err(|e| ArgoError::Provider(format!("memory fts delete: {e}")))?;
            sqlx::query("INSERT INTO memory_entry_fts(entry_id, body) VALUES (?, ?)")
                .bind(&entry_hex)
                .bind(&body)
                .execute(self.pool())
                .await
                .map_err(|e| ArgoError::Provider(format!("memory fts insert: {e}")))?;
            sqlx::query(
                "INSERT INTO memory_embedding (entry_id, model, dims, vector_json, created_at) \
                 VALUES (?, ?, ?, ?, ?) \
                 ON CONFLICT(entry_id) DO UPDATE SET model = excluded.model, \
                 dims = excluded.dims, vector_json = excluded.vector_json, \
                 created_at = excluded.created_at",
            )
            .bind(id.as_slice())
            .bind(provider.model())
            .bind(vector.len() as i64)
            .bind(vector_json)
            .bind(Utc::now().timestamp_micros())
            .execute(self.pool())
            .await
            .map_err(|e| ArgoError::Provider(format!("memory embedding upsert: {e}")))?;
        }
        Ok(())
    }

    async fn fts_scores(&self, query: &str) -> ArgoResult<HashMap<String, f64>> {
        let Some(fts) = fts_query(query) else {
            return Ok(HashMap::new());
        };
        let rows = sqlx::query(
            "SELECT entry_id, bm25(memory_entry_fts) AS rank \
             FROM memory_entry_fts WHERE memory_entry_fts MATCH ?",
        )
        .bind(fts)
        .fetch_all(self.pool())
        .await
        .map_err(|e| ArgoError::Provider(format!("memory fts query: {e}")))?;
        let mut out = HashMap::new();
        for row in rows {
            let entry_id: String = row
                .try_get("entry_id")
                .map_err(|e| ArgoError::Provider(format!("memory fts entry_id: {e}")))?;
            let rank: f64 = row
                .try_get("rank")
                .map_err(|e| ArgoError::Provider(format!("memory fts rank: {e}")))?;
            out.insert(entry_id, rank);
        }
        Ok(out)
    }
}

async fn memory_column_exists(pool: &sqlx::Pool<sqlx::Sqlite>, column: &str) -> ArgoResult<bool> {
    let rows = sqlx::query("PRAGMA table_info(memory_entry)")
        .fetch_all(pool)
        .await
        .map_err(|e| ArgoError::Provider(format!("memory table_info: {e}")))?;
    for row in rows {
        let name: String = row
            .try_get("name")
            .map_err(|e| ArgoError::Provider(format!("memory table_info name: {e}")))?;
        if name == column {
            return Ok(true);
        }
    }
    Ok(false)
}

async fn exec_schema(pool: &sqlx::Pool<sqlx::Sqlite>, sql: &str) -> ArgoResult<()> {
    sqlx::query(sql)
        .execute(pool)
        .await
        .map(|_| ())
        .map_err(|e| ArgoError::Provider(format!("memory layer schema: {e}")))
}

fn fts_query(query: &str) -> Option<String> {
    let mut terms = Vec::new();
    for term in query.split(|c: char| !c.is_ascii_alphanumeric()) {
        if term.len() < 2 {
            continue;
        }
        let lowered = term.to_ascii_lowercase();
        if !terms.contains(&lowered) {
            terms.push(lowered);
        }
        if terms.len() >= 8 {
            break;
        }
    }
    if terms.is_empty() {
        None
    } else {
        Some(
            terms
                .into_iter()
                .map(|term| format!("{term}*"))
                .collect::<Vec<_>>()
                .join(" OR "),
        )
    }
}

fn sha256(body: &str) -> [u8; 32] {
    let mut h = Sha256::new();
    h.update(body.as_bytes());
    let out = h.finalize();
    let mut buf = [0_u8; 32];
    buf.copy_from_slice(&out);
    buf
}
