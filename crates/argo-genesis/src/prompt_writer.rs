//! System prompt + persona prompt + memory schema + eval seed
//! writers. Template-driven; the LLM-driven refinement pass is
//! a near-term follow-up and slots into `pipeline` without
//! reshaping the orchestrator.

use crate::archetype::Archetype;
use crate::error::GenesisError;
use std::path::Path;

#[must_use]
pub fn build_system_prompt(charter: &str, archetype: Archetype, persona: &str) -> String {
    format!(
        "# System prompt — {label} worker `{persona}`\n\n\
         You are {persona}, a {label} working alongside the operator.\n\n\
         ## Charter (operator's words)\n\n{charter}\n\n\
         ## How to behave\n\n\
         - Plan before you act. Surface your plan to the operator before \
         dispatching any action that touches the outside world.\n\
         - Every action you emit must match an entry in the manifest's \
         `[actions]` vocabulary. Undeclared action_types will land \
         `blocked` rather than executing.\n\
         - Sensitive actions (send, post, pay, publish, delete, share, \
         message) ALWAYS require operator approval. Do not attempt to \
         autonomously dispatch them.\n\
         - Cite evidence for every claim. The OS's evidence gate \
         rejects emissions that lack a verifiable source.\n\n\
         ## Memory\n\n\
         You have three layers of memory: working, episodic, skills.\n\
         When you learn something the operator might want repeated, \
         propose a skill. The operator approves or declines.\n",
        label = archetype.label(),
        persona = persona,
        charter = charter,
    )
}

#[must_use]
pub fn build_persona_prompt(archetype: Archetype, persona: &str) -> String {
    format!(
        "# Persona — {persona}\n\n\
         **Name**: {persona}  \n\
         **Role**: {label}  \n\
         **Tone**: professional, warm, concise. Always sign messages with \
         `— {persona}`.\n\n\
         **What I'm not**: I'm not a chatbot, not a magic-8-ball, not the \
         operator. When asked something outside my charter, I escalate \
         rather than guess.\n\n\
         **Built by**: my operator, generated by the Skycot Worker OS \
         from a plain-English charter.\n",
        persona = persona,
        label = archetype.label(),
    )
}

#[must_use]
pub fn build_eval_seed(archetype: Archetype, _persona: &str) -> String {
    let mut out = String::new();
    for (label, prompt, expect) in eval_seed_rows(archetype) {
        let line = serde_json::json!({
            "id": format!("{}_{label}", archetype.slug()),
            "prompt": prompt,
            "expect_action_type": expect,
        });
        out.push_str(&line.to_string());
        out.push('\n');
    }
    out
}

fn eval_seed_rows(archetype: Archetype) -> Vec<(&'static str, String, &'static str)> {
    match archetype {
        Archetype::MarketingIntern => vec![
            (
                "draft_then_post",
                "Plan a launch tweet for our new feature".to_string(),
                "draft_campaign",
            ),
            (
                "research_first",
                "Research what's trending in the dev-tools space".to_string(),
                "research_topic",
            ),
        ],
        Archetype::CustomerSupportAgent => vec![(
            "triage_first",
            "An angry customer just filed a P0 ticket — what do you do?".to_string(),
            "triage_ticket",
        )],
        _ => vec![(
            "default",
            format!(
                "Show me how you'd handle a typical {} task",
                archetype.label().to_lowercase()
            ),
            "research_account",
        )],
    }
}

#[must_use]
pub fn build_memory_schema() -> String {
    "schema_version = \"1\"\n\n\
     [namespaces.working]\n\
     description = \"Per-task scratch memory; cleared at task end.\"\n\n\
     [namespaces.episodic]\n\
     description = \"Long-running context across sessions.\"\n\n\
     [namespaces.skills]\n\
     description = \"Operator-approved reusable procedures.\"\n"
        .to_string()
}

pub fn write_artefacts(
    dir: &Path,
    charter: &str,
    archetype: Archetype,
    persona: &str,
) -> Result<(), GenesisError> {
    let prompts_dir = dir.join("prompts");
    let memory_dir = dir.join("memory");
    let eval_dir = dir.join("eval");
    for d in [&prompts_dir, &memory_dir, &eval_dir] {
        std::fs::create_dir_all(d).map_err(|e| GenesisError::Io {
            what: "prompts.dir.create",
            source: e,
        })?;
    }
    write(
        &prompts_dir.join("system.md"),
        &build_system_prompt(charter, archetype, persona),
    )?;
    write(
        &prompts_dir.join("persona.md"),
        &build_persona_prompt(archetype, persona),
    )?;
    write(&memory_dir.join("schema.toml"), &build_memory_schema())?;
    write(&eval_dir.join("seed.jsonl"), &build_eval_seed(archetype, persona))?;
    Ok(())
}

fn write(path: &Path, body: &str) -> Result<(), GenesisError> {
    std::fs::write(path, body).map_err(|e| GenesisError::Io {
        what: "prompts.write",
        source: e,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn system_prompt_carries_charter_and_safety_rules() {
        let p = build_system_prompt("be my marketing intern", Archetype::MarketingIntern, "maya");
        assert!(p.contains("be my marketing intern"));
        assert!(p.contains("Marketing Intern"));
        assert!(p.contains("maya"));
        assert!(p.contains("approval"));
        assert!(p.contains("send"));
    }

    #[test]
    fn persona_prompt_includes_signoff() {
        let p = build_persona_prompt(Archetype::SalesSdr, "sam");
        assert!(p.contains("— sam"));
        assert!(p.contains("Sales SDR"));
    }

    #[test]
    fn eval_seed_is_valid_jsonl() {
        let body = build_eval_seed(Archetype::MarketingIntern, "maya");
        for line in body.lines() {
            let v: serde_json::Value = serde_json::from_str(line).unwrap();
            assert!(v.get("id").is_some(), "line missing id: {line}");
            assert!(v.get("prompt").is_some(), "line missing prompt: {line}");
        }
    }

    #[test]
    fn memory_schema_declares_three_namespaces() {
        let s = build_memory_schema();
        assert!(s.contains("[namespaces.working]"));
        assert!(s.contains("[namespaces.episodic]"));
        assert!(s.contains("[namespaces.skills]"));
    }

    #[test]
    fn write_artefacts_creates_full_layout() {
        let dir = tempfile::tempdir().unwrap();
        write_artefacts(
            dir.path(),
            "be my marketing intern",
            Archetype::MarketingIntern,
            "maya",
        )
        .unwrap();
        for relpath in [
            "prompts/system.md",
            "prompts/persona.md",
            "memory/schema.toml",
            "eval/seed.jsonl",
        ] {
            assert!(dir.path().join(relpath).exists(), "missing: {relpath}");
        }
    }
}
