//! Manifest writer — assembles a complete `vertical.toml` from
//! the archetype + persona + charter. Per-archetype seed
//! vocabularies live here; the safety judge enforces
//! `requires_approval` on sensitive verbs as a hard rule.

use crate::archetype::Archetype;
use crate::error::GenesisError;
use crate::safety_judge;
use argo_vertical::{
    ActionDeclaration, ActionRiskLevel, ActionsSection, ExecutorDeclaration, RoleSection,
    SuccessMetricsSection, VerticalIdentity, VerticalManifest, SCHEMA_VERSION,
};
use std::collections::BTreeMap;

/// Build the manifest TOML for a charter + archetype + persona.
pub fn build_manifest(
    charter: &str,
    archetype: Archetype,
    persona: &str,
    vertical_id: &str,
) -> Result<VerticalManifest, GenesisError> {
    let role = build_role(charter, archetype, persona);
    let mut actions = build_actions(archetype);

    safety_judge::auto_fix(&mut actions);
    safety_judge::judge(&actions)?;

    let manifest = VerticalManifest {
        schema_version: SCHEMA_VERSION.to_string(),
        vertical: VerticalIdentity {
            id: vertical_id.to_string(),
            name: format!("{} ({persona})", archetype.label()),
            version: "0.0.1".to_string(),
            description: format!("Generated by Genesis from charter: {charter}"),
            ..VerticalIdentity::default()
        },
        role: Some(role),
        actions: Some(actions),
        success_metrics: Some(build_success_metrics(archetype)),
        ..VerticalManifest::default()
    };
    Ok(manifest)
}

fn build_role(_charter: &str, _archetype: Archetype, _persona: &str) -> RoleSection {
    // The existing `RoleSection` schema (Stream A) holds only
    // path references to the prompts. The charter + KPIs live
    // elsewhere: charter in `VerticalIdentity.description`, KPIs
    // baked into `prompts/system.md`. This keeps Genesis from
    // having to expand the argo-vertical schema (which the
    // brief explicitly forbids).
    RoleSection {
        system_prompt: "prompts/system.md".to_string(),
        persona: Some("prompts/persona.md".to_string()),
    }
}

fn build_actions(archetype: Archetype) -> ActionsSection {
    let mut actions: BTreeMap<String, ActionDeclaration> = BTreeMap::new();
    for (name, risk, requires_approval, description) in seed_vocabulary(archetype) {
        actions.insert(
            name.to_string(),
            ActionDeclaration {
                risk,
                requires_approval,
                description: description.to_string(),
                executor: ExecutorDeclaration::default(),
                ..ActionDeclaration::default()
            },
        );
    }
    ActionsSection { actions }
}

fn build_success_metrics(_archetype: Archetype) -> SuccessMetricsSection {
    // v1 ships the standard SLA/CSAT skeleton. Operators tune
    // these values per-vertical after the worker's been live
    // for a week and there's real data.
    SuccessMetricsSection {
        deflection_target_pct: Some(70),
        median_response_seconds: Some(60),
        csat_threshold: Some(0.85),
        required_audit_chain_intact: Some(true),
    }
}

