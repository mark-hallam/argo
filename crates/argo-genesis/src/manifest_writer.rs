#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn build_manifest_for_marketing_intern_satisfies_safety_judge() {
        let m = build_manifest(
            "be my marketing intern",
            Archetype::MarketingIntern,
            "maya",
            "marketing_intern_maya",
        )
        .expect("manifest builds");
        assert_eq!(m.vertical.id, "marketing_intern_maya");
        let actions = m.actions.expect("actions present");
        assert!(actions.actions.contains_key("draft_campaign"));
        assert!(actions.actions["post_campaign"].requires_approval);
        assert!(actions.actions["send_followup"].requires_approval);
        assert!(!actions.actions["research_topic"].requires_approval);
    }

    #[test]
    fn every_archetype_seed_passes_safety_judge_after_auto_fix() {
        for a in Archetype::ALL {
            let m = build_manifest("test charter", *a, "test_persona", "test_id")
                .unwrap_or_else(|e| panic!("{} failed: {e}", a.label()));
            let actions = m.actions.expect("actions present");
            for (name, decl) in &actions.actions {
                if crate::safety_judge::matches_sensitive_verb(name) {
                    assert!(
                        decl.requires_approval,
                        "{}/{name} must require approval",
                        a.label()
                    );
                }
            }
        }
    }

    #[test]
    fn manifest_carries_charter_in_description() {
        // RoleSection only holds prompt path refs in the
        // existing schema; the charter rides in
        // `VerticalIdentity.description` so Genesis can attach
        // it without expanding the argo-vertical schema.
        let m = build_manifest(
            "be my custom charter",
            Archetype::SalesSdr,
            "sam",
            "sdr_sam",
        )
        .unwrap();
        assert!(m.vertical.description.contains("be my custom charter"));
    }
}
