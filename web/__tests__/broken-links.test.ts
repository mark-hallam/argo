import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * Link-checker — closes web-cleanup-broken-links-sweep.
 *
 * Static crawl of all visible href values in web/app/ + web/components/.
 * For every literal `/`-prefixed href (no template interpolation, no
 * external URL, no fragment, no mailto/tel), asserts that the path
 * resolves to one of:
 *   - a route file under `web/app/<path>/page.tsx` / `route.ts` /
 *     `route.tsx` / `layout.tsx`
 *   - a dynamic-segment route (the dir contains a `[…]` segment which
 *     matches the static path on the same depth)
 *   - the explicit allowlist below (special-format paths emitted by
 *     `app/icon.tsx` etc., or paths owned by middleware rewrites)
 *
 * Template-literal hrefs (`href={`/workers/${id}/...`}`) are skipped —
 * they belong to dynamic routes covered by the dynamic-segment check.
 *
 * Reason this exists: wave-4 404/500 audit found multiple visible links
 * that 404'd in prod (HelpWidget SLA / `/changelog/rss.xml` /
 * `/support`). A static check catches the regression class in CI before
 * it ships.
 */

const THIS_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(THIS_DIR, "..", "..");
const WEB_DIR = join(REPO_ROOT, "web");
const APP_DIR = join(WEB_DIR, "app");
const COMPONENTS_DIR = join(WEB_DIR, "components");

const SCAN_ROOTS = [APP_DIR, COMPONENTS_DIR];

// Paths the app deliberately serves outside the `app/` directory tree,
// or that the middleware handles. Keep this list short and justified.
const KNOWN_ROUTES_ALLOWLIST = new Set<string>([
  "/", // root → redirects via middleware/landing
  "/favicon.ico", // public/ asset
  "/icon", // generated by app/icon.tsx (Next.js metadata route)
  "/apple-icon", // generated by app/apple-icon.tsx
  "/opengraph-image", // generated by app/opengraph-image.tsx
  "/robots.txt", // generated by app/robots.ts
  "/sitemap.xml", // generated by app/sitemap.ts
  "/manifest.webmanifest", // generated by app/manifest.ts (if present)
]);

// Sections of the codebase whose href values are demonstrably not
// load-bearing user navigation (sample data fixtures, test scaffolding,
// docs templates). Exclude to keep the signal-to-noise ratio honest.
const FILE_SKIP_SUBSTRINGS = [
  "/sample-",
  "/__tests__/",
  ".test.ts",
  ".test.tsx",
  "/test-utils/",
];

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".")) continue;
    if (entry === "node_modules") continue;
    const full = join(dir, entry);
    const s = statSync(full);
    if (s.isDirectory()) {
      out.push(...walk(full));
    } else if (full.endsWith(".tsx") || full.endsWith(".ts")) {
      if (FILE_SKIP_SUBSTRINGS.some((sub) => full.includes(sub))) continue;
      out.push(full);
    }
  }
  return out;
}

// Match double-quoted, single-quoted, and JSX `href="…"` attribute
// values whose content is a literal string starting with `/`. Skips
// `href={…}` expression containers (template literals + variables).
const HREF_RE = /\bhref\s*=\s*(["'])(\/[^"'\s{}]*)\1/g;

function extractStaticHrefs(text: string): string[] {
  const hits: string[] = [];
  let m: RegExpExecArray | null;
  while ((m = HREF_RE.exec(text)) !== null) {
    hits.push(m[2]);
  }
  return hits;
}

function stripQueryAndHash(path: string): string {
  return path.replace(/[?#].*$/, "");
}

function routeFileExists(routePath: string): boolean {
  // routePath is something like "/sla" or "/changelog/rss.xml" or "/".
  const cleaned = stripQueryAndHash(routePath);
  if (KNOWN_ROUTES_ALLOWLIST.has(cleaned)) return true;

  const segments = cleaned.split("/").filter(Boolean);

  // Try literal segments first under (app), (hire), (setup), (auth route
  // group) and the bare root. Next.js's route group dirs (parenthesized)
  // are transparent to the URL, so search all of them.
  const candidateRoots = [
    APP_DIR,
    join(APP_DIR, "(app)"),
    join(APP_DIR, "(hire)"),
    join(APP_DIR, "(setup)"),
  ];

  for (const root of candidateRoots) {
    if (resolveRouteUnder(root, segments)) return true;
  }
  return false;
}

function resolveRouteUnder(root: string, segments: string[]): boolean {
  let cursor = root;
  if (!existsSync(cursor)) return false;

  for (let i = 0; i < segments.length; i++) {
    const seg = segments[i];
    const direct = join(cursor, seg);
    if (existsSync(direct) && statSync(direct).isDirectory()) {
      cursor = direct;
      continue;
    }
    // Try a dynamic-segment match: any `[…]` sibling directory absorbs
    // one path segment.
    const dyn = readdirSync(cursor).find(
      (e) =>
        (e.startsWith("[") && e.endsWith("]")) ||
        (e.startsWith("[[") && e.endsWith("]]")),
    );
    if (dyn) {
      cursor = join(cursor, dyn);
      continue;
    }
    return false;
  }

  // Cursor is now the directory that should host page.tsx / route.ts.
  return (
    existsSync(join(cursor, "page.tsx")) ||
    existsSync(join(cursor, "page.ts")) ||
    existsSync(join(cursor, "route.ts")) ||
    existsSync(join(cursor, "route.tsx"))
  );
}

describe("broken-links — closes web-cleanup-broken-links-sweep", () => {
  it("every literal /-prefixed href points to a real route", () => {
    const offenders = new Map<string, string[]>(); // href → files that reference it
    for (const root of SCAN_ROOTS) {
      if (!existsSync(root)) continue;
      for (const file of walk(root)) {
        const text = readFileSync(file, "utf8");
        const hrefs = extractStaticHrefs(text);
        for (const raw of hrefs) {
          const href = stripQueryAndHash(raw);
          if (href === "" || href.startsWith("#")) continue;
          if (routeFileExists(href)) continue;
          const list = offenders.get(href) ?? [];
          list.push(relative(REPO_ROOT, file));
          offenders.set(href, list);
        }
      }
    }
    const flat = [...offenders.entries()].map(
      ([href, files]) => `${href}  ← ${files.slice(0, 3).join(", ")}`,
    );
    expect(
      flat,
      "Broken hrefs found. Each line is `<href> ← <file(s)>`. Either add the route, fix the link target, or extend KNOWN_ROUTES_ALLOWLIST.",
    ).toEqual([]);
  });
});
