#!/usr/bin/env node
// Generates web/lib/pricing/tiers.data.json from the canonical pricing
// source of truth, docs/skycot/pricing/v1-tiers.toml (DEC-035 / DEC-053).
//
// The /pricing page and its copy DERIVE every number from this artifact —
// there are no hardcoded prices, allowances, or multipliers in the JSX. A
// browser bundle cannot read the .toml at runtime, so this build-time step
// projects the scalar tier fields into a committed JSON the client imports.
//
// Run `node scripts/gen-pricing-tiers.mjs` from web/, or rely on the
// `prebuild` hook. `web/tests/pricing-tiers-source.test.ts` fails if the
// committed JSON ever drifts from the .toml, so a stale checkout is caught
// in CI rather than shipping a wrong price.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const TOML_PATH = join(HERE, "..", "..", "docs", "skycot", "pricing", "v1-tiers.toml");
const OUT_PATH = join(HERE, "..", "lib", "pricing", "tiers.data.json");

// Scalar fields the pricing copy needs. Feature arrays + display_name stay in
// the .toml; the page derives feature copy from the numbers + DEC-053 model.
const SCALAR_FIELDS = [
  "price_monthly_usd",
  "max_workers",
  "max_actions_per_month",
  "included_actions",
  "overage_multiplier",
  "default_monthly_cap_usd",
];

/**
 * Minimal parser for the narrow, controlled v1-tiers.toml schema: top-level
 * `[section]` headers with `key = value` scalar lines. Multi-line feature
 * arrays and string values are ignored — only the scalar fields above are
 * projected. Not a general TOML parser; intentionally scoped to this file.
 */
export function parseTierScalars(toml) {
  const out = {};
  let section = null;
  for (const raw of toml.split("\n")) {
    const line = raw.replace(/#.*$/, "").trim();
    if (!line) continue;
    const header = line.match(/^\[(\w+)\]$/);
    if (header) {
      section = header[1];
      out[section] = {};
      continue;
    }
    if (!section) continue;
    const kv = line.match(/^(\w+)\s*=\s*(.+)$/);
    if (!kv) continue;
    const [, key, rawVal] = kv;
    if (!SCALAR_FIELDS.includes(key)) continue;
    const val = rawVal.trim();
    if (!/^-?\d+(\.\d+)?$/.test(val)) continue;
    out[section][key] = Number(val);
  }
  return out;
}

export function buildTiersData(toml) {
  const scalars = parseTierScalars(toml);
  return {
    _comment: "GENERATED by web/scripts/gen-pricing-tiers.mjs from docs/skycot/pricing/v1-tiers.toml — do not edit by hand.",
    free: scalars.free,
    pro: scalars.pro,
    enterprise: scalars.enterprise,
  };
}

function main() {
  const toml = readFileSync(TOML_PATH, "utf8");
  const data = buildTiersData(toml);
  writeFileSync(OUT_PATH, JSON.stringify(data, null, 2) + "\n", "utf8");
  // eslint-disable-next-line no-console
  console.log(`gen-pricing-tiers: wrote ${OUT_PATH}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
